"""Draw the README charts from committed result files. Standard library only, one SVG per
result, so the pictures regenerate from the numbers and never drift from them.

    python benchmarks/charts.py benchmarks/results/2026-09-28-premarket.json
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BG, INK, MUTED, GRID = "#0d1117", "#e6edf3", "#8b949e", "#30363d"
COLORS = {"rest": "#8b949e", "picks": "#3fb950"}
LABELS = {"nifty 50": "NIFTY 50", "s&p 500": "S&P 500", "dax": "DAX", "bank nifty": "BANK NIFTY"}
FONT = 'font-family="ui-sans-serif, system-ui, -apple-system, Segoe UI, Helvetica, Arial, sans-serif"'


def esc(s) -> str:
    return str(s).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")


def grouped_bars(title: str, subtitle: str, note: str, groups: list[dict], legend: dict[str, str], max_v: float = 50, width: int = 860) -> str:
    left, top, bottom, right = 70, 96, 84, 30
    plot_w, plot_h = width - left - right, 300
    height = top + plot_h + bottom
    arms = list(legend)
    group_w = plot_w / len(groups)
    bar_w = min(64, (group_w - 60) / len(arms))
    y = lambda v: top + plot_h - min(v, max_v) / max_v * plot_h  # noqa: E731
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}" role="img" aria-label="{esc(title)}">',
           f'<rect width="{width}" height="{height}" rx="12" fill="{BG}"/>',
           f'<text x="{width / 2}" y="34" text-anchor="middle" {FONT} font-size="17" font-weight="600" fill="{INK}">{esc(title)}</text>',
           f'<text x="{width / 2}" y="56" text-anchor="middle" {FONT} font-size="12" fill="{MUTED}">{esc(subtitle)}</text>']
    lx = width / 2 - 140 * len(arms) / 2
    for i, arm in enumerate(arms):
        x = lx + i * 170
        out.append(f'<rect x="{x}" y="70" width="12" height="12" rx="2" fill="{COLORS[arm]}"/>')
        out.append(f'<text x="{x + 18}" y="81" {FONT} font-size="12" fill="{INK}">{esc(legend[arm])}</text>')
    for t in range(0, int(max_v) + 1, 10):
        out.append(f'<line x1="{left}" y1="{y(t)}" x2="{width - right}" y2="{y(t)}" stroke="{GRID}" stroke-width="1"/>')
        out.append(f'<text x="{left - 10}" y="{y(t) + 4}" text-anchor="end" {FONT} font-size="11" fill="{MUTED}">{t}%</text>')
    for gi, g in enumerate(groups):
        gx = left + gi * group_w + (group_w - bar_w * len(arms) - 12 * (len(arms) - 1)) / 2
        for ai, arm in enumerate(arms):
            b = g["bars"][arm]
            x = gx + ai * (bar_w + 12)
            out.append(f'<rect x="{x:.1f}" y="{y(b["value"]):.1f}" width="{bar_w:.1f}" height="{top + plot_h - y(b["value"]):.1f}" rx="3" fill="{COLORS[arm]}"/>')
            out.append(f'<text x="{x + bar_w / 2:.1f}" y="{y(b["value"]) - 8:.1f}" text-anchor="middle" {FONT} font-size="13" font-weight="600" fill="{INK}">{b["value"]:.0f}%</text>')
            out.append(f'<text x="{x + bar_w / 2:.1f}" y="{top + plot_h + 18:.1f}" text-anchor="middle" {FONT} font-size="11" fill="{MUTED}">{esc(b["text"])}</text>')
        out.append(f'<text x="{left + gi * group_w + group_w / 2:.1f}" y="{top + plot_h + 42:.1f}" text-anchor="middle" {FONT} font-size="14" font-weight="600" fill="{INK}">{esc(g["label"])}</text>')
    out.append(f'<text x="{width / 2}" y="{height - 14}" text-anchor="middle" {FONT} font-size="11" fill="{MUTED}">{esc(note)}</text>')
    out.append("</svg>")
    return "\n".join(out) + "\n"


def premarket(path: Path) -> Path:
    doc = json.loads(path.read_text(encoding="utf-8"))
    groups = []
    for m in doc["markets"]:
        groups.append({"label": LABELS.get(m["market"], m["market"].upper()),
                       "bars": {"rest": {"value": 100 * m["big_move_others"], "text": f'{m["big_moves_others"]}/{m["others"]}'},
                                "picks": {"value": 100 * m["big_move_picks"], "text": f'{m["big_moves_picks"]}/{m["picks"]}'}}})
    first = min(m["first_session"] for m in doc["markets"])
    last = max(m["last_session"] for m in doc["markets"])
    svg = grouped_bars(
        title="Pre-market scan: share of stocks that made a big move that session",
        subtitle=f'walk-forward, {doc["sessions_per_market"]} sessions per market ({first} to {last}), top {doc["top_k"]} picks a day chosen from earlier data only',
        note=f'big move: {doc["big_move_definition"]}. Generated by benchmarks/charts.py from {path.name}.',
        groups=groups, legend={"rest": "rest of the market", "picks": "tradefloor's top 5 picks"})
    out = ROOT / "assets" / "benchmark-premarket.svg"
    out.write_text(svg, encoding="utf-8", newline="\n")
    return out


if __name__ == "__main__":
    for arg in sys.argv[1:]:
        print("wrote", premarket(Path(arg)).relative_to(ROOT).as_posix())
