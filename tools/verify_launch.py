"""Repeatable local release checks; external checks never publish or make model calls."""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tomllib

ROOT = Path(__file__).resolve().parents[1]


def _private_keys(value):
    if isinstance(value, dict):
        for key, child in value.items():
            if key.lower() in {"api_key", "authorization", "access_token", "refresh_token", "credentials"}:
                raise ValueError("Public fixture contains a credential field")
            _private_keys(child)
    elif isinstance(value, list):
        for child in value:
            _private_keys(child)


def verify_artifact(path):
    from tradefloor import demo, runs
    html = Path(path).read_text(encoding="utf-8")
    prefix = "window.DEMO_DATA="
    if html.count(prefix) != 1:
        raise ValueError("Expected one frozen demo payload")
    payload = json.JSONDecoder().raw_decode(html.split(prefix, 1)[1])[0]
    expected = {f"{case}:{preset}" for case in ("earnings", "policy", "liquidity") for preset in demo.PRESETS}
    if not isinstance(payload, dict) or set(payload) != expected:
        raise ValueError("Demo must contain all 21 expected frozen examples")
    _private_keys(payload)
    bundles = {}
    current_engine = runs.digest({p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(Path(runs.__file__).parent.glob("*.py"))})
    for label, response in payload.items():
        bundle = runs.verify(json.loads(response["bundle_json"]))
        if bundle["runtime"]["source_sha256"] != current_engine:
            raise ValueError("Static receipts were built from a different engine revision")
        if bundle["request"]["case"] != label.split(":")[0] or response["result"].get("case") != bundle["request"]["case"]:
            raise ValueError("Static event label differs from its frozen request")
        if bundle["kind"] != "scenario" or bundle["result"]["symbol"] != "SYNTHETIC":
            raise ValueError("Public demo contains a non-synthetic research receipt")
        if bundle["inputs"]["prices"].get("rights") != "synthetic fixture generated by MIT project code":
            raise ValueError("Public demo contains unapproved data rights")
        if response["result"].get("symbol") != "SYNTHETIC" or response["result"]["run"].get("path"):
            raise ValueError("Rendered fixture is non-synthetic or exposes a local path")
        if response["result"]["run"]["sha256"] != bundle["sha256"]:
            raise ValueError("Displayed run hash differs from its receipt")
        bundles[label] = bundle
    if len({bundle["id"] for bundle in bundles.values()}) != 21:
        raise ValueError("Static fixtures reuse a run identity")
    for label, bundle in bundles.items():
        case, preset = label.split(":")
        if preset == "original" and bundle["parent"] is not None:
            raise ValueError("Original fixture unexpectedly has an ancestor")
        if preset != "original" and bundle["parent"] != bundles[f"{case}:original"]["id"]:
            raise ValueError("Precomputed fork has incorrect lineage")
    if any(marker in html for marker in ("/*DATA*/", "/*STYLE*/", "/*APP*/", "/*MODEL*/", "/*DESK*/", "<!--DESK_PANELS-->")):
        raise ValueError("Static artifact has uninlined assets")
    if re.search(r"<script\b[^>]*\bsrc\s*=", html, re.I):
        raise ValueError("Standalone demo unexpectedly depends on an external script")
    if html != demo.workspace_document(payload):
        raise ValueError("Standalone UI differs from the current packaged assets; rebuild the demo")
    return {"receipts": len(bundles), "bytes": len(html.encode()), "sha256": hashlib.sha256(Path(path).read_bytes()).hexdigest()}


def verify_checksums(directory, version):
    root = Path(directory)
    checksum_path = root / f"SHA256SUMS-v{version}.txt"
    wanted = {f"tradefloor-{version}-py3-none-any.whl", f"tradefloor-{version}.tar.gz", "demo/index.html"}
    seen = set()
    for line in checksum_path.read_text(encoding="utf-8").splitlines():
        digest, name = line.split("  ", 1)
        if name not in wanted or name in seen or not re.fullmatch(r"[a-f0-9]{64}", digest):
            raise ValueError("Checksum manifest has an unexpected or duplicate artifact")
        if hashlib.sha256((root / name).read_bytes()).hexdigest() != digest:
            raise ValueError(f"Release checksum differs: {name}")
        seen.add(name)
    if seen != wanted:
        raise ValueError("Release checksum manifest is incomplete")
    return {"artifacts": len(seen)}


def command(args, timeout=180):
    completed = subprocess.run(args, cwd=ROOT, capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=timeout)
    if completed.returncode:
        raise ValueError((completed.stdout + completed.stderr)[-2500:].strip() or "Check command failed")
    return completed.stdout.strip()[-1500:]


def check(report, name, fn):
    try:
        report["checks"][name] = {"status": "passed", "details": fn()}
    except Exception as error:
        report["checks"][name] = {"status": "failed", "details": str(error)[:2500]}


def run(args):
    version = tomllib.loads((ROOT / "server/pyproject.toml").read_text(encoding="utf-8"))["project"]["version"]
    report = {"schema": "tradefloor-launch-check-v1", "version": version,
              "checked_at": datetime.now(timezone.utc).isoformat(), "checks": {},
              "forecasting_skill_verified": False, "published_by_this_check": False}
    if args.artifact_only:
        check(report, "synthetic_static_artifact", lambda: verify_artifact(ROOT / args.artifact))
        report["local_release_checks_passed"] = report["checks"]["synthetic_static_artifact"]["status"] == "passed"
        report["public_launch_verified"] = False
        Path(args.output).parent.mkdir(parents=True, exist_ok=True)
        Path(args.output).write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
        return report
    check(report, "generated_host_files", lambda: command([sys.executable, "tools/build.py", "--check"]))
    check(report, "synthetic_static_artifact", lambda: verify_artifact(ROOT / args.artifact))
    check(report, "distribution_checksums", lambda: verify_checksums(ROOT / "dist", version))
    check(report, "python_lint", lambda: command([sys.executable, "-m", "ruff", "check", "--select", "F,E9", "server/src/tradefloor"]))
    if args.tests:
        check(report, "python_tests", lambda: command([sys.executable, "-m", "pytest", "-q", "tests", "server/tests"], timeout=300))
    else:
        report["checks"]["python_tests"] = {"status": "not_run", "details": "Use --tests for the full suite on this revision"}
    node = shutil.which("node")
    if node:
        def frontend():
            for file in ("app.js", "workspace.js", "workspace-model.js", "desk.js", "research-map-model.js", "research-map.js", "source-view.js", "sources.js"):
                command([node, "--check", f"server/src/tradefloor/assets/{file}"])
            return command([node, "--test", "tests/frontend.test.cjs", "tests/workspace-model.test.cjs", "tests/research-map.test.cjs", "tests/sources.test.cjs"])
        check(report, "frontend_tests_and_syntax", frontend)
    else:
        report["checks"]["frontend_tests_and_syntax"] = {"status": "blocked", "details": "Node is unavailable"}
    try:
        report["revision"] = command(["git", "rev-parse", "HEAD"])
        dirty = bool(command(["git", "status", "--porcelain"]))
        report["checks"]["reviewed_source_revision"] = {"status": "blocked" if dirty else "passed",
            "details": "Working tree changes need review/commit before publishing" if dirty else "Working tree matches the recorded revision"}
    except Exception:
        report["checks"]["reviewed_source_revision"] = {"status": "blocked", "details": "Git revision could not be verified"}
    report["checks"]["live_model_calls"] = {"status": "not_run", "details": "Skipped by request" if args.skip_live else "Live calls require a separately configured connection and explicit execution"}
    if args.github:
        try:
            pages = json.loads(command(["gh", "api", f"repos/{args.github}/pages"]))
            report["checks"]["public_pages_configuration"] = {"status": "configured", "details": {"url": pages.get("html_url"), "build_type": pages.get("build_type"), "status": pages.get("status")}}
        except Exception:
            report["checks"]["public_pages_configuration"] = {"status": "blocked", "details": "Pages is not configured or could not be inspected with the available GitHub access"}
    else:
        report["checks"]["public_pages_configuration"] = {"status": "not_run", "details": "Use --github OWNER/REPO for read-only Pages inspection"}
    report["checks"]["public_browser_qa"] = {"status": "not_run", "details": "Requires a deployed URL and real-browser verification"}
    local = ("generated_host_files", "synthetic_static_artifact", "distribution_checksums", "python_lint", "frontend_tests_and_syntax")
    if args.tests:
        local += ("python_tests",)
    report["local_release_checks_passed"] = all(report["checks"][name]["status"] == "passed" for name in local)
    report["public_launch_verified"] = False
    Path(args.output).parent.mkdir(parents=True, exist_ok=True)
    Path(args.output).write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    return report


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--artifact", default="dist/demo/index.html")
    parser.add_argument("--output", default="dist/launch-check.json")
    parser.add_argument("--tests", action="store_true")
    parser.add_argument("--artifact-only", action="store_true", help="Verify a synthetic-only static export without requiring wheel artifacts")
    parser.add_argument("--skip-live", action="store_true")
    parser.add_argument("--github", help="Read-only Pages check for OWNER/REPO")
    args = parser.parse_args()
    if args.github and not re.fullmatch(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+", args.github):
        parser.error("--github must be OWNER/REPO")
    result = run(args)
    print(json.dumps({"report": args.output, "local_release_checks_passed": result["local_release_checks_passed"], "public_launch_verified": False}))
    sys.exit(0 if result["local_release_checks_passed"] else 1)
