def antigravity_mcp() -> dict:
    # Antigravity reads mcp_config.json from a plugin root but, as of agy 1.1.16, expands no
    # path variable and starts servers in the workspace. So its plugin fetches the server by
    # git URL, pinned to this release's tag. tools/install.py antigravity is the local route.
    src = f"git+{REPO}@v{version()}#subdirectory=server"
    return {"mcpServers": {NAME: {"command": "uvx", "args": ["--from", src, "tradefloor-mcp"]}}}


# ---------------------------------------------------------------- the full set

def targets() -> dict[str, str]:
    out: dict[str, str] = {}
    body = read("rules/tradefloor.md")
    for path, render in RULE_TARGETS.items():
        out[path] = render(body)
    for r in roles():
        out[f"agents/{r['name']}.md"] = agent_portable(r)
        out[f"hosts/claude/agents/{r['name']}.md"] = agent_claude(r)
        for skill in DESK_SKILLS[r["desk"]]:
            out[f"skills/{skill}/references/{r['name']}.md"] = role_reference(r)
    out[".claude-plugin/plugin.json"] = js(claude_plugin())
    out[".claude-plugin/marketplace.json"] = js(marketplace("https://json.schemastore.org/claude-code-marketplace.json", "finance"))
    out["plugin.json"] = js(agent_plugin())  # Agent Plugins 1.0: Codex; Antigravity requires it
    out["mcp.json"] = js(agent_plugin_mcp())  # Codex, via .codex-plugin/plugin.json
    out[".codex-plugin/plugin.json"] = js(codex_plugin())
    out["mcp_config.json"] = js(antigravity_mcp())  # Antigravity plugins read this name
    return out


