def marketplace(schema: str | None, category: str) -> dict:
    out = {"name": NAME, "description": "tradefloor: a multi-agent trading desk for any market.",
           "owner": {"name": "Himanshu Jangir", "url": "https://github.com/HimanshuJ16"},
           "plugins": [{"name": NAME, "source": "./", "description": DESCRIPTION, "category": category,
                        "tags": ["trading", "stocks", "indices", "multi-agent", "global-markets"]}]}
    return {"$schema": schema, **out} if schema else out


def agent_plugin() -> dict:
    """Agent Plugins 1.0 root manifest: Codex, Copilot CLI, Cursor, Devin, VS Code and other conforming clients."""
    return {
        "$schema": "https://agent-plugins.org/schemas/1.0.0/plugin.schema.json",
        **meta(),
        "extensions": {"com.openai": {"interface": codex_interface()}},
    }


def agent_plugin_mcp() -> dict:
    return {"$schema": "https://agent-plugins.org/schemas/1.0.0/mcp.schema.json",
            "mcpServers": {NAME: {"type": "stdio", "command": "uv", "args": server_args("${PLUGIN_ROOT}")}}}


