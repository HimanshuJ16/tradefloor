def version() -> str:
    text = (ROOT / "server" / "pyproject.toml").read_text(encoding="utf-8")
    return re.search(r'^version = "([^"]+)"', text, re.M).group(1)


def server_args(root: str) -> list[str]:
    """How every host launches the server. `root` is the host's plugin-root expression.

    `python -m`, not the `tradefloor-mcp` console script: on Windows a running server locks
    its script's .exe, and uv rewrites console scripts whenever it reinstalls the package,
    so a second session or an update would fail to start while the first one runs."""
    return ["run", "--quiet", "--project", f"{root}/server", "python", "-m", "tradefloor.server"]


def lf(text: str) -> str:
    return text.replace("\r\n", "\n")


def read(rel: str) -> str:
    return lf((ROOT / rel).read_text(encoding="utf-8"))


def js(obj) -> str:
    return json.dumps(obj, indent=2, ensure_ascii=False) + "\n"


def meta(**extra) -> dict:
    return {"name": NAME, "version": version(), "description": DESCRIPTION, "author": AUTHOR,
            "homepage": REPO, "repository": REPO, "license": "MIT", "keywords": KEYWORDS, **extra}


# ---------------------------------------------------------------- roles

def parse_role(path: Path) -> dict:
    m = re.match(r"---\n(.*?)\n---\n\n?(.*)", lf(path.read_text(encoding="utf-8")), re.S)
    fm = dict(line.split(": ", 1) for line in m.group(1).splitlines())
    fm["body"] = m.group(2).rstrip() + "\n"
    fm["src"] = f"roles/{path.name}"
    return fm


def roles() -> list[dict]:
    return [parse_role(p) for p in sorted((ROOT / "roles").glob("*.md"))]


def _fm(fields: dict) -> str:
    return "---\n" + "\n".join(f"{k}: {v}" for k, v in fields.items()) + "\n---\n"


def agent_portable(r: dict) -> str:
    # name + description only: the subset Gemini CLI, Devin, Cursor and Grok all accept.
    return _fm({"name": r["name"], "description": r["description"]}) + f"\n<!-- {NOTE.format(src=r['src'])} -->\n\n" + r["body"]


def agent_claude(r: dict) -> str:
    denied = "Bash, Edit, NotebookEdit" + (", WebSearch, WebFetch" if r["web"] == "never" else "")
    return _fm({
        "name": r["name"], "description": r["description"],
        "model": "inherit" if r["tier"] == "deep" else "sonnet",
        "disallowedTools": denied, "color": r["color"],
    }) + f"\n<!-- {NOTE.format(src=r['src'])} -->\n\n" + r["body"]


DESK_SKILLS = {"analyze": ["analyze"], "scout": ["scout"], "both": ["analyze", "scout"]}


def role_reference(r: dict) -> str:
    return (f"<!-- {NOTE.format(src=r['src'])} -->\n\n# Role: {r['name']}\n\n"
            f"Play this role yourself when your host has no `{r['name']}` subagent.\n\n" + r["body"])


